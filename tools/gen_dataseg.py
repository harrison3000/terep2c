#!/usr/bin/env python3
"""Generate src/dataseg.hpp from src/dataseg.def.

The original program keeps (almost) all of its state in one 64 KB data
segment and addresses it by absolute offsets.  dataseg.def lists what the
port still keeps there, with the original's offsets (as documentation, and
checked here for overlaps with the original sizes below); this script turns
it into a plain struct, in the same order.

dataseg.def format, one field per line:
    OFFSET  TYPE  NAME[COUNT]   ; comment
TYPE is a type name (int16_t, Particle, ...); SIZES below has the sizes
the custom types had in the original.
"""
import re, sys, os

SIZES = {
    'int8_t': 1, 'uint8_t': 1, 'char': 1,
    'int16_t': 2, 'uint16_t': 2,
    'int32_t': 4, 'uint32_t': 4,
    'Vec3': 12, 'Pos': 12, 'ChaseCam': 0x12, 'Particle': 0x1c, 'ProjVertex': 10,
    'PolyVertex': 8, 'ScanEdge': 4, 'Point2': 4, 'Angles': 6, 'Q15': 2,
    'PcxHeader': 128, 'SpriteQuad': 0x12, 'PolyBuf': 0x52, 'PointBuf': 0x2a,
}

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'src')
fields = []
for ln, line in enumerate(open(os.path.join(src, 'dataseg.def')), 1):
    line = line.rstrip()
    if not line.strip() or line.lstrip().startswith(';'):
        continue
    code, _, comment = line.partition(';')
    m = re.match(r'\s*(0x[0-9a-fA-F]+)\s+(\w+)\s+(\w+)((?:\[\w+\])*)\s*$', code)
    if not m:
        sys.exit('dataseg.def:%d: bad line: %s' % (ln, line))
    off = int(m.group(1), 16)
    typ, name = m.group(2), m.group(3)
    dims = [int(x, 0) for x in re.findall(r'\[(\w+)\]', m.group(4))]
    count = dims or None
    size = SIZES[typ]
    for d in dims:
        size *= d
    fields.append((off, typ, name, count, size, comment.strip()))

fields.sort()
out = []
out.append('/* GENERATED by tools/gen_dataseg.py from src/dataseg.def - do not edit */')
out.append('#pragma once')
out.append('')
out.append('struct DataSeg {')
pos = 0
for off, typ, name, count, size, comment in fields:
    if off < pos:
        sys.exit('overlap at %s (0x%x < 0x%x)' % (name, off, pos))
    decl = '    %s %s%s;' % (typ, name, ''.join('[%d]' % d for d in (count or [])))
    if comment:
        decl = decl.ljust(44) + ' /* %04x: %s */' % (off, comment)
    else:
        decl = decl.ljust(44) + ' /* %04x */' % off
    out.append(decl)
    pos = off + size
if pos > 0x10000:
    sys.exit('data segment overflows 64K')
out.append('};')
open(os.path.join(src, 'dataseg.hpp'), 'w').write('\n'.join(out) + '\n')
print('dataseg.hpp: %d fields' % len(fields))
